export type IconName = keyof typeof ICONS

export function Icon({ name, size = 32 }: { name: IconName; size?: number }) {
  const rows = ICONS[name]
  const rects: JSX.Element[] = []
  rows.forEach((row, y) =>
    [...row].forEach((ch, x) => {
      const fill = P[ch]
      if (fill) rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={fill} />)
    }),
  )
  return (
    <svg width={size} height={size} viewBox="0 0 16 16" shapeRendering="crispEdges" aria-hidden>
      {rects}
    </svg>
  )
}
